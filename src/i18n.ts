const LANG_KEY = 'splitsplash.lang';
const initial = localStorage.getItem(LANG_KEY) ?? (navigator.language.toLowerCase().startsWith('it') ? 'it' : 'en');

i18n.use(initReactI18next).init({
  resources: { it: { translation: it }, en: { translation: en } },
  lng: initial,
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
});

document.documentElement.lang = initial;

export function toggleLanguage() {
  const next = i18n.language === 'it' ? 'en' : 'it';
  localStorage.setItem(LANG_KEY, next);
  document.documentElement.lang = next;
  void i18n.changeLanguage(next);
}

export function errorKey(code: string): string {
  return `errors.${code in it.errors ? code : 'generic'}`;
}

export default i18n;
