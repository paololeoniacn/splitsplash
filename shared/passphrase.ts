const ALL_WORDS: readonly string[] = [...PASSPHRASE_WORDS, ...HABITAT_WORDS];

function randomInt(max: number): number {
  const limit = Math.floor(0x1_0000_0000 / max) * max;
  const buf = new Uint32Array(1);
  for (;;) {
    crypto.getRandomValues(buf);
    if (buf[0] < limit) return buf[0] % max;
  }
}

export const PASSPHRASE_WORD_COUNT = 5;

/** Five words from animals + habitats and four digits ≈ 53 bits (258⁵·10⁴). Plain a–z/0–9/-, so it is URL-safe as is. */
export function generatePassphrase(): string {
  const words = Array.from({ length: PASSPHRASE_WORD_COUNT }, () => ALL_WORDS[randomInt(ALL_WORDS.length)]);
  const digits = String(randomInt(10000)).padStart(4, '0');
  return [...words, digits].join('-');
}

/** Case/accents/separators-insensitive canonical form: "Volpe Koala.gufo 0042" → "volpe-koala-gufo-0042". */
export function normalizePassphrase(input: string): string {
  return input
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean)
    .join('-');
}

/** Accepts the current format and the legacy three-word one, so older rooms keep working. */
export function isPassphraseShape(input: string): boolean {
  return /^([a-z]+-){3,6}\d{4}$/.test(normalizePassphrase(input));
}

/** Rooms created before the five-word format should be nudged to rotate. */
export function isLegacyPassphrase(passphrase: string): boolean {
  return normalizePassphrase(passphrase).split('-').length - 1 < PASSPHRASE_WORD_COUNT;
}

export const RECOVERY_WORD_COUNT = 8;

/** Personal keyring recovery code: eight animal/habitat words ≈ 64 bits (258⁸). Never stored, only hashed. */
export function generateRecoveryCode(): string {
  return Array.from({ length: RECOVERY_WORD_COUNT }, () => ALL_WORDS[randomInt(ALL_WORDS.length)]).join('-');
}

export function isRecoveryShape(input: string): boolean {
  return new RegExp(`^([a-z]+-){${RECOVERY_WORD_COUNT - 1}}[a-z]+$`).test(normalizePassphrase(input));
}
